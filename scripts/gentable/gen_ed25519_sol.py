import re
P=2**255-19
txt=open('/tmp/tbl2.txt').read()
rows=re.findall(r'j == (\d+)\) return \((0x[0-9a-f]+), (0x[0-9a-f]+), (0x[0-9a-f]+)\)',txt)
assert len(rows)==30
stores=[]
for n,(j,a,b,c) in enumerate(rows):
    j=int(j); base=0 if n<15 else 1536
    for i,val in enumerate((a,b,c)):
        stores.append(f"            mstore(add(tbl, {base+(j*3+i)*32}), {val})")
DBL='''                {
                    let aa := mulmod(x, x, P)
                    let bb := mulmod(y, y, P)
                    let cc := mulmod(z, z, P)
                    cc := add(cc, cc)                          // C = 2 Z^2, < 2p
                    let s := add(x, y)                         // < 2p
                    let h := sub(P2, add(aa, bb))              // H = D - B = -A - B, in (0, 2p]
                    let e := addmod(mulmod(s, s, P), h, P)     // E = (X+Y)^2 - A - B
                    let g := addmod(bb, sub(P, aa), P)         // G = D + B = B - A
                    let f := addmod(g, sub(P2, cc), P)         // F = G - C
                    x := mulmod(e, f, P)
                    y := mulmod(g, h, P)
                    z := mulmod(f, g, P)
                    %T%
                }
'''
ADD='''                if j {
                    let o := add(%BASE%, mul(j, 96))
                    let A := mulmod(addmod(y, sub(P, x), P), mload(add(o, 32)), P) // (Y-X)(y-x)
                    let B := mulmod(add(y, x), mload(o), P)                        // (Y+X)(y+x)
                    let C := mulmod(t, mload(add(o, 64)), P)                       // T * 2dxy
                    let D := add(z, z)                                             // < 2p
                    let E := addmod(B, sub(P, A), P)
                    let F := addmod(D, sub(P, C), P)
                    let G := addmod(D, C, P)
                    let H := addmod(B, A, P)
                    x := mulmod(E, F, P)
                    y := mulmod(G, H, P)
                    z := mulmod(F, G, P)
                    t := mulmod(E, H, P)
                }
'''
loop = DBL.replace('%T%','')*3 + DBL.replace('%T%','t := mulmod(e, h, P)') \
     + "                j := and(shr(sh, k), 15)\n" + ADD.replace('%BASE%','tbl') \
     + "                j := and(shr(add(sh, 128), k), 15)\n" + ADD.replace('%BASE%','add(tbl, 1536)')
src='''// SPDX-License-Identifier: MIT
// TEST-ONLY. NOT AUDITED.
pragma solidity 0.8.26;

/// @notice Fixed-base scalar multiplication on ed25519 (the curve Monero uses),
///         written from the curve definition (RFC 8032 parameters) and the
///         extended-coordinate formulas of Hisil-Wong-Carter-Dawson 2008
///         ("Twisted Edwards Curves Revisited": dbl-2008-hwcd, madd-2008-hwcd-3,
///         a = -1; complete for ed25519 because d is not a square).
///         Only used to check that a revealed secret k satisfies k*B == P for a
///         public key P committed when the swap was created, so it does NOT need
///         to be constant-time (the secret is public once submitted).
///         Tables j*B and j*2^128*B (j = 1..15, affine-niels form y+x, y-x, 2dxy)
///         are generated by scripts/gentable (math/big) and the results are
///         checked against filippo.io/edwards25519 in tests.
library Ed25519 {
    uint256 internal constant P = 0x7fffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffed;
    /// group order l = 2^252 + 27742317777372353535851937790883648493
    uint256 internal constant L = 0x1000000000000000000000000000000014def9dea2f79cd65812631a5cf5d3ed;
    uint256 private constant P2 = %P2%; // 2p

    /// @return enc the standard 32-byte Monero/ed25519 encoding of k*B, read as a
    ///         LITTLE-ENDIAN integer: y | (x & 1) << 255. Reverts on k == 0 or k >= l.
    /// Method: k = hi*2^128 + lo; 32 rounds of (4 doublings, + lo-window*B,
    /// + hi-window*2^128*B), starting from the identity (formulas are complete).
    /// All mulmod/addmod inputs are < 2^256; subtraction is addmod(a, kp - b), b < kp.
    function mulBaseEncoded(uint256 k) internal view returns (uint256 enc) {
        require(k != 0 && k < L, "ed25519: bad scalar");
        uint256 X;
        uint256 Y;
        uint256 Z;
        assembly ("memory-safe") {
            let tbl := mload(0x40) // scratch above the free pointer; not allocated, not kept
%STORES%
            let x := 0
            let y := 1
            let z := 1
            let t := 0
            let j := 0
            for { let sh := 128 } sh { } {
                sh := sub(sh, 4)
%LOOP%            }
            X := x
            Y := y
            Z := z
        }
        uint256 zi = _inv(Z);
        uint256 xa = mulmod(X, zi, P);
        uint256 ya = mulmod(Y, zi, P);
        enc = ya | ((xa & 1) << 255);
    }

    /// z^(p-2) mod p via the MODEXP precompile (0x05).
    function _inv(uint256 z) private view returns (uint256 r) {
        require(z != 0, "ed25519: z=0");
        assembly ("memory-safe") {
            let m := mload(0x40)
            mstore(m, 32)
            mstore(add(m, 0x20), 32)
            mstore(add(m, 0x40), 32)
            mstore(add(m, 0x60), z)
            mstore(add(m, 0x80), sub(P, 2))
            mstore(add(m, 0xa0), P)
            if iszero(staticcall(gas(), 0x05, m, 0xc0, m, 0x20)) { revert(0, 0) }
            r := mload(m)
        }
    }
}
'''
src=src.replace('%P2%',hex(2*P)).replace('%STORES%',"\n".join(stores)).replace('%LOOP%',loop)
open('src/Ed25519.sol','w').write(src)
